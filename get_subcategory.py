import os
import psycopg2
from psycopg2.extras import RealDictCursor
from typing import List
from config.env_loader import load_environment, load_db_config



def get_unique_subcategories() -> List[str]:
    """
    products.sub_category 컬럼의 DISTINCT 값을 리스트로 반환한다.
    접속 정보는 POSTGRES_* 환경 변수에서 읽어온다.
    """
    conn = psycopg2.connect(
        **db_config
    )

    query = """
        SELECT DISTINCT subcategory
        FROM   products
        WHERE  subcategory IS NOT NULL
        ORDER  BY subcategory;
    """

    try:
        with conn, conn.cursor(cursor_factory=RealDictCursor) as cur:
            cur.execute(query)
            rows = cur.fetchall()
            # rows = [{'sub_category': '슬리브리스'}, {'sub_category': '니트'}, ...]
            return [row["subcategory"] for row in rows]
    finally:
        conn.close()



